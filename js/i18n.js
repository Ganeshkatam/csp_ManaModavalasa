let currentLanguage = localStorage.getItem('csp_language') || 'en';

function getLanguage() {
    return currentLanguage;
}

function setLanguage(lang) {
    if (lang !== 'en' && lang !== 'te') lang = 'en';
    currentLanguage = lang;
    localStorage.setItem('csp_language', lang);
    applyTranslations();
    document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function toggleLanguage() {
    setLanguage(currentLanguage === 'en' ? 'te' : 'en');
}

function t(key) {
    const dict = I18N_DICT[currentLanguage] || I18N_DICT.en;
    return dict[key] || I18N_DICT.en[key] || key;
}

// Return localized field or fallback to English field
function getLocalized(item, field) {
    if (!item) return '';
    if (currentLanguage === 'te') {
        const teVal = item[field + '_te'];
        if (teVal && teVal.trim().length > 0) {
            return teVal;
        }
    }
    return item[field] || '';
}

function applyTranslations() {
    // Translate text of all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.textContent = t(key);
    });

    // Translate placeholder attributes
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.setAttribute('placeholder', t(key));
    });

    // Translate title/aria-label attributes
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        el.setAttribute('title', t(key));
    });

    // Update language toggle button text
    const langBtn = document.getElementById('btnLangToggle');
    if (langBtn) {
        langBtn.textContent = currentLanguage === 'en' ? 'తెలుగు' : 'English';
    }

    // Set document lang attribute
    document.documentElement.lang = currentLanguage;
}

// Initialize on DOMContentLoaded
document.addEventListener('DOMContentLoaded', () => {
    applyTranslations();
    const langBtn = document.getElementById('btnLangToggle');
    if (langBtn) {
        langBtn.addEventListener('click', (e) => {
            e.preventDefault();
            toggleLanguage();
        });
    }
});
